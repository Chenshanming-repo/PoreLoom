#!/usr/bin/env python3
"""Generate manuscript mean +/- sample-SD macros from verified unit summaries."""
from pathlib import Path
from statistics import mean, stdev
import csv
import json
import re
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
summary = json.loads((ROOT / 'review/mean_sd_summary.json').read_text())
budget_summary = json.loads((ROOT / 'review/supp_experiment_tables_audit.json').read_text())['budget']
macros = {}
audit = {}


def select(section, **keys):
    rows = [row for row in summary[section] if all(row[k] == str(v) for k, v in keys.items())]
    assert len(rows) == 1, (section, keys, len(rows))
    return rows[0]


def add(name, stat, scale=100, digits=2):
    m, s = stat['mean'] * scale, stat['sd'] * scale
    macros[name] = rf'\ensuremath{{{m:.{digits}f} \pm {s:.{digits}f}}}'
    audit[name] = {'mean': m, 'sample_sd': s, 'n': 3}


for family, tag in [('Simulated', 'Sim'), ('R9', 'Rnine'), ('R10 mixed', 'Mix'), ('R10 sputum', 'Sputum')]:
    for method, short in [('poreloom', 'PL'), ('readcurrent', 'RC'), ('nanodeep_upstream', 'ND'), ('squigglenet', 'SN')]:
        row = select('overall', family=family, method=method, variant='streaming' if method == 'poreloom' else 'w6000')
        for key, suffix in [('acc', 'Acc'), ('host_reject', 'Reject'), ('frr', 'Frr'), ('host_pore', 'Pore')]:
            add(tag + short + suffix, row[key], 1 if key == 'host_pore' else 100, 3 if key == 'host_pore' else 2)

for dataset, tag, maximum in [('r10_run01', 'MixBudget', 18000), ('sputum_g1', 'SputumBudget', 12000)]:
    for budget, point in [(6000, 'Base'), (maximum, 'Max')]:
        row = select('budget', dataset=dataset, budget=budget)
        for key, suffix in [('acc', 'Acc'), ('frr', 'Frr'), ('host_pore', 'Pore')]:
            add(tag + point + suffix, row[key], 1 if key == 'host_pore' else 100, 3 if key == 'host_pore' else 2)
        forced_rows = [value for value in budget_summary if value['dataset'] == dataset and value['budget'] == budget]
        assert len(forced_rows) == 1
        add(tag + point + 'HostForced', forced_rows[0]['host_forced_fraction'])

for fraction, tag in [(10, 'One'), (100, 'Ten'), (300, 'Thirty')]:
    add('Yield' + tag, select('simulation', strategy='PoreLoom', permille=fraction)['relative_yield'], 1)

with (ROOT / 'figure_data/timing_raw.csv').open() as handle:
    timing = list(csv.DictReader(handle))
for scenario, tag, prefix in [('mixed', 'Mixed', -1), ('aligned', 'Aligned', 19200)]:
    paired = {}
    for method, suffix in [('incremental', 'Inc'), ('scratch', 'Full')]:
        rows = [r for r in timing if r['scenario'] == scenario and r['chunk'] == '1600' and r['batch'] == '512' and (scenario == 'mixed' or r['n'] == str(prefix)) and r['method'] == method]
        assert len(rows) == 3 and len({r['rep'] for r in rows}) == 3
        values = [float(r['seconds']) for r in rows]
        paired[method] = {r['rep']: float(r['seconds']) for r in rows}
        add('Timing' + tag + suffix, {'mean': mean(values), 'sd': stdev(values)}, 1000, 1)
    ratios = [paired['scratch'][rep] / paired['incremental'][rep] for rep in paired['scratch']]
    add('Timing' + tag + 'Ratio', {'mean': mean(ratios), 'sd': stdev(ratios)}, 1, 2)

# Scalar dataset endpoints and conditional decision-position fractions.
prefix_values = pd.read_csv(ROOT / 'figure_data/fixed_prefix.csv')
position_values = pd.read_csv(ROOT / 'figure_data/decision_position_summary.csv')
hosts = [row['host_reject']['mean'] for row in summary['overall'] if row['method'] == 'poreloom']
macros['MainPLMinReject'] = f'{100 * min(hosts):.2f}'
macros['MainPLMaxReject'] = f'{100 * max(hosts):.2f}'
for family, tag in [('Simulated', 'Sim'), ('R9', 'Rnine'), ('R10 mixed', 'Mix'), ('R10 sputum', 'Sputum')]:
    for length, point in [(432, 'Base'), (6000, 'Max')]:
        values = prefix_values[(prefix_values.family == family) & (prefix_values.usable_samples == length)]
        macros[tag + 'Prefix' + point + 'Acc'] = f"{100 * values.acc.mean():.2f}"
    positions = position_values[(position_values.family == family) & (position_values.category == 'all')]
    for key, suffix in [('fraction_by_3000', 'DecisionByThree'), ('no_decision_fraction', 'NoDecision')]:
        macros[tag + suffix] = f"{100 * positions[key].mean():.2f}"
for fraction, tag in [(10, 'One'), (100, 'Ten'), (300, 'Thirty')]:
    values = [row['relative_yield']['mean'] for row in summary['simulation']
              if row['strategy'].endswith('_w6000') and row['permille'] == str(fraction)]
    macros['YieldWsixBest' + tag] = f'{max(values):.2f}'

(ROOT / 'numbers.tex').write_text('% Generated by scripts/prepare_summary_numbers.py; SD uses ddof=1, n=3.\n' + '\n'.join('\\newcommand{\\' + key + '}{' + value + '}' for key, value in macros.items()) + '\n')
(ROOT / 'review/numerical_mean_sd_audit.json').write_text(json.dumps(audit, indent=2) + '\n')
print(f'Wrote {len(audit)} mean-SD macros; range endpoints remain dataset means.')
